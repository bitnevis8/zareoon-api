function formatMoney(amount, currency) {
  const n = Number(amount);
  const formatted = Number.isFinite(n)
    ? n.toLocaleString("fa-IR", { maximumFractionDigits: 4 })
    : String(amount ?? "—");
  return `${formatted} ${currency || ""}`.trim();
}

